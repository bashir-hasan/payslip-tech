declare(strict_types=1);
/**
 * PaySlip.tech one-time installer.
 * Creates config.php, the database tables, the platform admin and (optionally) a demo company.
 * After installing, this file refuses to run again. You can delete it.
 */
define('ROOT', __DIR__);
define('APP', __DIR__ . '/core');
define('APP_VERSION', '1.9.0');

$installed = is_file(ROOT . '/config.php');
$errors = [];
$done = false;

function h($s) { return htmlspecialchars((string)$s, ENT_QUOTES, 'UTF-8'); }

$checks = [
    'PHP 8.1 or newer' => version_compare(PHP_VERSION, '8.1.0', '>='),
    'PDO MySQL extension' => extension_loaded('pdo_mysql'),
    'mbstring extension' => extension_loaded('mbstring'),
    'OpenSSL extension' => extension_loaded('openssl'),
    'cURL extension (for Polar billing)' => extension_loaded('curl'),
    'Folder is writable (for config.php)' => is_writable(ROOT),
    'uploads/logos is writable' => is_writable(ROOT . '/uploads/logos'),
];

$scheme = ((!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https')) ? 'https' : 'http';
$guessUrl = $scheme . '://' . ($_SERVER['HTTP_HOST'] ?? 'localhost') . rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? '/')), '/');

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    $in = fn($k) => trim((string)($_POST[$k] ?? ''));
    $cfg = [
        'db_host' => $in('db_host') ?: 'localhost',
        'db_port' => (int)($in('db_port') ?: 3306),
        'db_name' => $in('db_name'),
        'db_user' => $in('db_user'),
        'db_pass' => (string)($_POST['db_pass'] ?? ''),
        'app_url' => rtrim($in('app_url'), '/'),
        'app_key' => bin2hex(random_bytes(32)),
        'timezone' => 'Asia/Dhaka',
        'debug' => false,
    ];
    $adminName = $in('admin_name');
    $adminEmail = strtolower($in('admin_email'));
    $adminPass = (string)($_POST['admin_pass'] ?? '');

    if (in_array(false, $checks, true)) $errors[] = 'Fix the server requirements shown above first.';
    if ($cfg['db_name'] === '' || $cfg['db_user'] === '') $errors[] = 'Database name and user are required.';
    if (!filter_var($cfg['app_url'], FILTER_VALIDATE_URL)) $errors[] = 'Enter the full site URL, e.g. https://payslip.tech';
    if (strlen($adminName) < 2) $errors[] = 'Enter the admin name.';
    if (!filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter a valid admin email.';
    if (strlen($adminPass) < 10) $errors[] = 'Admin password must be at least 10 characters.';

    if (!$errors) {
        try {
            $pdo = new PDO(sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $cfg['db_host'], $cfg['db_port'], $cfg['db_name']), $cfg['db_user'], $cfg['db_pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            $sql = file_get_contents(APP . '/schema.sql');
            foreach (array_filter(array_map('trim', explode(';', $sql))) as $stmt) $pdo->exec($stmt);
        } catch (Throwable $e) {
            $errors[] = 'Database error: ' . $e->getMessage();
        }
    }

    if (!$errors) {
        $php = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . ". Keep this file private.\nreturn " . var_export($cfg, true) . ";\n";
        if (file_put_contents(ROOT . '/config.php', $php) === false) {
            $errors[] = 'Could not write config.php. Check folder permissions.';
        } else {
            @chmod(ROOT . '/config.php', 0640);
            $GLOBALS['CONFIG'] = $cfg;
            date_default_timezone_set('Asia/Dhaka');
            require APP . '/helpers.php';
            require APP . '/db.php';
            require APP . '/i18n.php';
            require APP . '/auth.php';
            require APP . '/payroll.php';
            require APP . '/security.php';
            require APP . '/seo.php';
            require APP . '/migrate.php';
            require APP . '/locale.php';
            require APP . '/billing.php';
            require APP . '/chatbot.php';
            require APP . '/blog.php';
            require APP . '/seed.php';
            if (!db_val('SELECT 1 FROM users WHERE email = ?', [$adminEmail])) {
                db_insert('users', ['role' => 'admin', 'name' => $adminName, 'email' => $adminEmail, 'password_hash' => password_hash($adminPass, PASSWORD_DEFAULT), 'status' => 'active', 'lang' => 'en', 'created_at' => date('Y-m-d H:i:s')]);
            }
            set_setting('site_name', 'PaySlip.tech');
            set_setting('support_email', $adminEmail);
            set_setting('allow_registration', '1');
            set_setting('demo_enabled', '0');
            run_migrations();
            if (!empty($_POST['demo'])) seed_demo();
            $done = true;
        }
    }
}
